create extension if not exists vector with schema extensions;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null unique,
  display_name text,
  created_at timestamptz not null default now()
);

create table if not exists public.business_settings (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  name text,
  address text,
  email text,
  phone text,
  tax_id text,
  logo_path text,
  default_currency text not null default 'USD',
  default_tax_pct double precision not null default 0.0,
  payment_terms text not null default 'Net 30',
  bank_name text,
  account_name text,
  account_number text,
  routing_number text,
  payment_notes text,
  default_email_subject varchar(200) not null default 'Invoice {invoice_number}',
  default_email_message text not null default E'Hello {client_name},\n\nPlease find invoice {invoice_number} attached.\n\nBest,\n{business_name}',
  onboarding_completed_at timestamptz,
  updated_at timestamptz not null default now(),
  constraint uq_business_settings_user_id unique (user_id),
  constraint ck_business_settings_email_subject_not_blank check (length(btrim(default_email_subject)) > 0),
  constraint ck_business_settings_email_message_not_blank check (length(btrim(default_email_message)) > 0),
  constraint ck_business_settings_email_message_length check (char_length(default_email_message) <= 5000)
);

create table if not exists public.clients (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  name text not null,
  client_code text,
  address text,
  email text,
  phone text,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint uq_clients_user_id_client_code unique (user_id, client_code)
);

create table if not exists public.client_addresses (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  client_id bigint not null references public.clients(id) on delete cascade,
  label text,
  address text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.catalog_items (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  description text not null,
  unit_price double precision not null default 0.0,
  unit text not null default 'item',
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.invoice_records (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  client_id bigint references public.clients(id) on delete set null,
  client_invoice_sequence integer,
  filename text not null,
  file_path text not null,
  storage_path text,
  source text not null,
  invoice_number text,
  client_name text,
  issue_date text,
  grand_total double precision,
  currency text not null default 'USD',
  rag_doc_id text,
  status text not null default 'draft',
  invoice_json text,
  created_at timestamptz not null default now(),
  constraint valid_source check (source in ('uploaded', 'generated')),
  constraint uq_invoice_records_user_client_sequence unique (user_id, client_id, client_invoice_sequence)
);

create table if not exists public.invoice_embeddings (
  id bigint generated by default as identity primary key,
  doc_id uuid not null,
  user_id uuid not null references public.profiles(id) on delete cascade,
  invoice_record_id bigint not null references public.invoice_records(id) on delete cascade,
  filename text not null,
  chunk_index integer not null,
  content text not null,
  embedding extensions.vector(1536) not null,
  created_at timestamptz not null default now(),
  constraint uq_invoice_embeddings_doc_chunk unique (doc_id, chunk_index)
);

create table if not exists public.invoice_emails (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  invoice_record_id bigint not null references public.invoice_records(id) on delete cascade,
  recipient_email text not null,
  cc_email text,
  subject text not null,
  message_body text not null,
  status text not null default 'pending',
  provider text not null default 'smtp',
  provider_message_id text,
  idempotency_key varchar(128),
  request_fingerprint varchar(64),
  attempt_count integer not null default 0,
  attempt_token varchar(36),
  lease_expires_at timestamptz,
  error_message text,
  sent_at timestamptz,
  created_at timestamptz not null default now(),
  constraint uq_invoice_emails_user_idempotency unique (user_id, idempotency_key)
);

create table if not exists public.security_events (
  id bigserial primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  event_type varchar(64) not null,
  outcome varchar(16) not null constraint ck_security_events_outcome check (outcome in ('allowed', 'blocked')),
  request_id varchar(128),
  created_at timestamptz not null default now()
);

create table if not exists public.subscriptions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  plan varchar(32) not null default 'free',
  status varchar(32) not null default 'free',
  stripe_customer_id varchar(255),
  stripe_subscription_id varchar(255),
  stripe_price_id varchar(255),
  superseded_subscription_ids text[] not null default '{}'::text[],
  current_period_end timestamptz,
  cancel_at_period_end boolean not null default false,
  last_event_created_at bigint,
  checkout_idempotency_key varchar(64),
  checkout_idempotency_created_at timestamptz,
  checkout_session_id varchar(255),
  checkout_session_expires_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint ck_subscriptions_plan check (plan in ('free', 'pro')),
  constraint uq_subscriptions_user_id unique (user_id),
  constraint uq_subscriptions_customer unique (stripe_customer_id),
  constraint uq_subscriptions_subscription unique (stripe_subscription_id)
);

create table if not exists public.stripe_webhook_events (
  event_id varchar(255) primary key,
  event_type varchar(255) not null,
  event_created_at bigint not null,
  processed_at timestamptz not null default now()
);

create table if not exists public.usage_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  feature varchar(32) not null,
  tokens_in integer not null default 0,
  tokens_out integer not null default 0,
  audio_seconds integer not null default 0,
  estimated_cost_micros bigint not null default 0,
  request_id varchar(128),
  created_at timestamptz not null default now(),
  constraint ck_usage_events_feature check (feature in ('ai_text', 'voice')),
  constraint ck_usage_events_tokens_in check (tokens_in >= 0),
  constraint ck_usage_events_tokens_out check (tokens_out >= 0),
  constraint ck_usage_events_audio_seconds check (audio_seconds >= 0),
  constraint ck_usage_events_estimated_cost_micros check (estimated_cost_micros >= 0)
);

create table if not exists public.usage_pack_credits (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  pack_kind varchar(32) not null,
  tokens_remaining bigint not null default 0,
  voice_seconds_remaining bigint not null default 0,
  stripe_checkout_session_id varchar(255) not null,
  stripe_payment_intent_id varchar(255),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint ck_usage_pack_credits_kind check (pack_kind in ('ai_tokens', 'voice_seconds')),
  constraint ck_usage_pack_tokens_remaining check (tokens_remaining >= 0),
  constraint ck_usage_pack_voice_seconds_remaining check (voice_seconds_remaining >= 0),
  constraint uq_usage_pack_credits_checkout_session unique (stripe_checkout_session_id)
);

